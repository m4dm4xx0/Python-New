# Typecasting = the process of converting a variable from one data type to another
#               str(), int(), float(), bool()

name = 'Lydia'
age = 25
gpa = 4.2
is_student = True

print(type(name))
print(type(age))
print(type(gpa))
print(type(is_student))


gpa = str(gpa)
print(type(gpa))

name = bool(name)
print(type(name))
print(name)
